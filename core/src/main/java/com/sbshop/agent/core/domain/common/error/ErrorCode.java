package com.sbshop.agent.core.domain.common.error;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

@Getter
@RequiredArgsConstructor
public enum ErrorCode {

  // ======================================================================
  // 400 Bad Request
  // ======================================================================
  INVALID_INPUT_VALUE(400, "CMM400", "올바르지 않은 입력값입니다."),
  INVALID_TYPE_VALUE(400, "CMM401", "타입이 일치하지 않습니다."),
  MISSING_PARAMETER(400, "CMM402", "필수 파라미터가 누락되었습니다."),

  // ======================================================================
  // 401 Unauthorized (인증)
  // ======================================================================
  UNAUTHORIZED(401, "CMM410", "인증되지 않은 사용자입니다."),
  TOKEN_EXPIRED(401, "CMM411", "토큰이 만료되었습니다."),
  INVALID_TOKEN(401, "CMM412", "유효하지 않은 토큰입니다."),

  // ======================================================================
  // 403 Forbidden (권한)
  // ======================================================================
  ACCESS_DENIED(403, "CMM430", "접근 권한이 없습니다."),

  // ======================================================================
  // 404 Not Found (리소스 없음)
  // ======================================================================
  RESOURCE_NOT_FOUND(404, "CMM440", "요청한 리소스를 찾을 수 없습니다."),
  PAGE_NOT_FOUND(404, "CMM441", "존재하지 않는 페이지입니다."),

  // ======================================================================
  // 405 Method Not Allowed
  // ======================================================================
  METHOD_NOT_ALLOWED(405, "CMM450", "허용되지 않은 HTTP 메서드입니다."),

  // ======================================================================
  // 409 Conflict (상태 충돌 / 중복)
  // ======================================================================
  RESOURCE_CONFLICT(409, "CMM490", "리소스가 이미 존재하거나 상태가 충돌했습니다."),
  INVALID_STATE(409, "CMM491", "현재 상태에서는 수행할 수 없는 작업입니다."),

  // ======================================================================
  // 500 Internal Server Error (서버 내부 에러)
  // ======================================================================
  INTERNAL_SERVER_ERROR(500, "CMM500", "서버 내부 오류가 발생했습니다."),
  FILE_UPLOAD_FAILED(500, "CMM501", "파일 업로드에 실패했습니다."),

  // ======================================================================
  // 502/503 External & AI Service (외부 연동)
  // ======================================================================
  EXTERNAL_API_ERROR(502, "EXT502", "외부 시스템 연동 중 오류가 발생했습니다."),
  AI_SERVICE_ERROR(503, "EXT503", "AI 서비스 응답이 지연되거나 오류가 발생했습니다.");

  private final int status;
  private final String code;
  private final String message;
}